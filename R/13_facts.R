# Every number quoted in the note, appendix and methods memo, computed from pipeline output
# and written to data/out/note_facts.csv. The documents read this file through inline R, so no
# number is typed by hand.

suppressPackageStartupMessages({
  library(dplyr)
  library(readr)
})
source("R/utils.R")
source("R/fn_owner_managers.R")

facts <- list()
add <- function(key, value, note = "") facts[[key]] <<- tibble(key = key, value = as.numeric(value), note = note)
m3 <- function(f) read_codes_csv(out_path("m3", f))

# AEI and usage-based exposure -----------------------------------------------------
je <- read_csv(raw_path("aei", "job_exposure.csv"), show_col_types = FALSE)
soc_all <- soc2018_detailed_codes()
add("je_rows", nrow(je))
add("je_zero", sum(je$observed_exposure == 0))
add("je_zero_share", mean(je$observed_exposure == 0))
add("je_max", max(je$observed_exposure))
add("je_mean", mean(je$observed_exposure))
add("je_median", median(je$observed_exposure))
add("soc_total", length(soc_all))
add("soc_missing", length(setdiff(soc_all, je$occ_code)))
rc <- read_codes_csv(out_path("m1", "aei_row_counts.csv"))
add("aei_rows_aus", sum(rc$n_rows[rc$geo_id == "AUS"]))
add("aei_rows_wa", sum(rc$n_rows[rc$geo_id == "AU-WA"]))
add("aei_months", n_distinct(rc$period))
mm <- m3("aei_major_group_missing_mass.csv")
for (g in c("AUS", "AU-WA", "GLOBAL")) {
  k <- c(AUS = "aus", `AU-WA` = "wa", GLOBAL = "global")[[g]]
  add(paste0("mg_pub_min_", k), min(mm$published_pct[mm$geo_id == g]) / 100)
  add(paste0("mg_pub_max_", k), max(mm$published_pct[mm$geo_id == g]) / 100)
  add(paste0("mg_groups_min_", k), min(mm$groups_published[mm$geo_id == g]))
  add(paste0("mg_groups_max_", k), max(mm$groups_published[mm$geo_id == g]))
}
socm <- read_codes_csv(interim_path("soc_measures.csv"))
add("soc_with_beta", sum(!is.na(socm$beta_gpt4)))
add("soc_with_automation", sum(!is.na(socm$global_automation_pct)))

# Employment ----------------------------------------------------------------------
emp <- read_codes_csv(interim_path("emp_units.csv"))
eqc <- read_codes_csv(out_path("m1", "eq08_row_counts.csv"))
add("units", nrow(emp))
add("emp_total_m", sum(emp$emp) / 1000)
add("emp_wa_m", sum(emp$emp_wa) / 1000)
add("eq08_quarters", nrow(eqc))
add("nfd_share_min", min(eqc$nfd_share))
add("nfd_share_max", max(eqc$nfd_share))
add("eq08_codes_max", max(eqc$codes))
add("eq08_nfd_codes_max", max(eqc$nfd_codes))
alloc <- read_codes_csv(out_path("m1", "eq08_nfd_allocation_log.csv"))
add("nfd_fallback_persons", 1000 * sum(alloc$nfd_emp_000_avg[alloc$rule != "cell"]))

# Earnings ------------------------------------------------------------------------
earn <- read_codes_csv(interim_path("earnings_units.csv"))
add("eeh_direct", sum(!is.na(earn$eeh_weekly_p_raw)))
add("eeh_imputed", sum(earn$eeh_imputed != "none"))
add("eeh_rse25", sum(earn$eeh_rse_max > 0.25, na.rm = TRUE))
add("eeh13_missing", sum(is.na(earn$eeh13_hourly_p)))
ato <- read_codes_csv(out_path("m2", "ato_code_lookup.csv"))
add("ato_codes", nrow(ato))
add("ato_codes_2022", sum(ato$mapping == "ANZSCO 2022 unit group, bridged to v1.2"))
add("ato_codes_other", sum(ato$mapping != "ANZSCO 2022 unit group, bridged to v1.2"))
add("ato_unmapped_share", sum(ato$share_of_individuals[ato$mapping != "ANZSCO 2022 unit group, bridged to v1.2"]))
add("ato_blank_share", ato$share_of_individuals[ato$code == "0000"])
add("ato_imputed", sum(earn$ato_imputed != "none"))

# Bridges and crosswalks -------------------------------------------------------------
br <- read_codes_csv(interim_path("bridge_2022units_v12units.csv"))
add("bridge_pairs", nrow(br))
add("bridge_same", sum(br$type == "same code"))
add("bridge_recoded", sum(br$type == "recoded one-to-one"))
add("bridge_merge", sum(grepl("^merge", br$type)))
add("bridge_split", sum(grepl("^split", br$type)))
add("bridge_m2m", sum(br$type == "many-to-many"))
jsa <- read_codes_csv(interim_path("jsa_units.csv"))
add("jsa_units", nrow(jsa))
w <- read_codes_csv(interim_path("soc_weights_oews.csv"))
add("oews_direct", sum(w$source == "OEWS detailed"))
add("oews_broad", sum(grepl("^OEWS broad", w$source)))
add("oews_fallback", sum(grepl("^no OEWS row", w$source)))
add("oews_none", length(soc_all) - nrow(w))
l1 <- read_codes_csv(interim_path("links_scheme1_isco.csv"))
add("links1", nrow(l1))
add("links1_isco", n_distinct(unlist(strsplit(l1$isco_codes, ";"))))
val <- read_codes_csv(out_path("m2", "chain_validation_summary.csv"))
add("val_identical", val$identical_link_sets)
add("val_differ", val$differ)
t3 <- read_codes_csv(out_path("m2", "scheme3_title_matches.csv"))
add("s3_occupations", n_distinct(t3$anzsco6))
add("s3_units", n_distinct(substr(t3$anzsco6, 1, 4)))
l4 <- read_codes_csv(interim_path("links_scheme4_lmi.csv"))
add("links4", nrow(l4))
add("s4_units", n_distinct(l4$unit))
add("s4_poor", sum(l4$strength == "POOR"))

# Coverage and grades ------------------------------------------------------------------
cov <- read_codes_csv(out_path("coverage.csv"))
add("coverage", cov$coverage_share)
add("units_covered", cov$units_covered)
add("units_unmatched", cov$units_total - cov$units_covered)
g <- read_codes_csv(interim_path("unit_grades.csv")) |> left_join(emp |> select(unit, emp_share), by = "unit")
for (gr in c("one-to-one", "few-to-one", "diffuse")) {
  k <- gsub("-", "", gr)
  add(paste0("grade_n_", k), sum(g$grade == gr))
  add(paste0("grade_emp_", k), sum(g$emp_share[g$grade == gr]))
}
add("owner_manager_units", length(owner_manager_draft))

# Results used in the memo (descriptive figures only) -----------------------------------
dp <- m3("decile_profiles.csv") |> filter(scheme == "s1", sample == "all", ranking == "eeh") |> arrange(decile)
add("usage_d1", dp$usage[1]); add("usage_d10", dp$usage[10])
add("ext_d1", dp$extensive[1]); add("ext_d10", dp$extensive[10])
add("tmb_pp", 100 * (dp$usage[10] - dp$usage[1]))
sens <- m3("sensitivity_table.csv")
add("specs", nrow(sens)); add("specs_hold", sum(sens$holds))
add("specs_hold_s4", sum(sens$holds[sens$scheme == "s4"])); add("specs_s4", sum(sens$scheme == "s4"))
ci <- m3("concentration_indices.csv")
for (m in ci$measure) add(paste0("ci_", m), ci$ci[ci$measure == m])
cor <- m3("correlations.csv") |> filter(scheme == "s1")
for (p in cor$potential) add(paste0("rho_", p), cor$spearman_weighted[cor$potential == p])
inf <- m3("influence_largest_units.csv")
add("s4_tmb", inf$top_minus_bottom_pp[inf$scheme == "s4" & inf$left_out == "none"])
add("s4_tmb_no6211", inf$top_minus_bottom_pp[inf$scheme == "s4" & inf$left_out == "6211"])
add("emp_share_6211", emp$emp_share[emp$unit == "6211"])

out <- bind_rows(facts)
write_csv(out, out_path("note_facts.csv"))
message("Facts written: ", nrow(out))
